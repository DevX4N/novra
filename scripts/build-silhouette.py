"""
Turns the traced X-01 side profile (scripts/side-profile.json) into SVG path
data for the line-art silhouette (src/content/silhouette.ts).

The silhouette shares the coordinate space of public/media/reveal-side.webp
(1672 x 941), so it lines up exactly with that photograph.

Usage:  python scripts/build-silhouette.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = json.loads((ROOT / "scripts" / "side-profile.json").read_text())


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def smooth(points, closed=False, tension=0.5, corner_deg=38):
    """Catmull-Rom to cubic Bezier, keeping sharp corners sharp."""
    pts = points[:] + ([points[0]] if closed else [])
    n = len(pts)

    def angle(i):
        if i <= 0 or i >= n - 1:
            return 180
        ax, ay = pts[i - 1][0] - pts[i][0], pts[i - 1][1] - pts[i][1]
        bx, by = pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]
        d = math.hypot(ax, ay) * math.hypot(bx, by) or 1
        return math.degrees(math.acos(max(-1, min(1, (ax * bx + ay * by) / d))))

    sharp = [angle(i) < 180 - corner_deg for i in range(n)]
    d = f"M{f(pts[0][0])} {f(pts[0][1])}"
    for i in range(n - 1):
        p0 = pts[i - 1] if i > 0 and not sharp[i] else pts[i]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[i + 2] if i + 2 < n and not sharp[i + 1] else p2
        k = tension / 3 * 2
        c1 = (p1[0] + (p2[0] - p0[0]) * k / 2, p1[1] + (p2[1] - p0[1]) * k / 2)
        c2 = (p2[0] - (p3[0] - p1[0]) * k / 2, p2[1] - (p3[1] - p1[1]) * k / 2)
        d += f" C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}"
    return d + (" Z" if closed else "")


def arc(cx, cy, r, a0, a1):
    x0, y0 = cx + r * math.cos(math.radians(a0)), cy + r * math.sin(math.radians(a0))
    x1, y1 = cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1))
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{f(x0)} {f(y0)} A{f(r)} {f(r)} 0 {large} 1 {f(x1)} {f(y1)}"


def circle(cx, cy, r):
    return f"M{f(cx - r)} {f(cy)} a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0 a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0"


upper = [[105,576],[90,563],[70,505],[65,478],[100,432],[100,410],[96,395],[96,382],[150,368],[205,360],
         [260,353],[322,345],[380,329],[442,317],[505,303],[567,291],[630,281],[692,274],[755,270],[817,269],
         [867,270],[905,275],[942,295],[1005,319],[1067,344],[1130,364],[1160,369],[1250,382],[1305,392],
         [1355,407],[1405,425],[1455,442],[1505,462],[1550,482],[1585,501]]
nose = [[1585,501],[1565,512],[1567,530],[1562,540],[1565,552],[1580,575],[1605,587],[1617,594],[1615,600],
        [1590,603],[1505,607],[1334,614]]
(rx, ry, rr), (fx, fy, fr) = P["wheels"]

paths = {
    # Outer body line, drawn as one continuous stroke.
    "body": " ".join([
        smooth(upper),
        smooth(nose, corner_deg=25),
        smooth([[1080,614],[760,609],[414,603]]),
        smooth([[168,589],[105,576]]),
        arc(rx, ry, rr + 12, 168, 372),
        arc(fx, fy, fr + 12, 172, 368),
    ]),
    "wing": smooth(P["wing"], closed=True, corner_deg=30),
    "glass": smooth(P["glass"], closed=True, corner_deg=30),
    "wheels": " ".join([circle(rx, ry, rr), circle(fx, fy, fr), circle(rx, ry, 84), circle(fx, fy, 84),
                        circle(rx, ry, 9), circle(fx, fy, 9)]),
    # Light signature: side blade, headlight and tail light.
    "lights": " ".join([smooth([[664,429],[860,531]]), smooth([[1390,461],[1470,472],[1540,488]]),
                        smooth([[100,388],[165,392]])]),
}

out = ROOT / "src" / "content" / "silhouette.ts"
body = ",\n".join(f"  {k}: \"{v}\"" for k, v in paths.items())
out.write_text(
    "// Generated by scripts/build-silhouette.py from the traced X-01 side profile.\n"
    "// Coordinates match public/media/reveal-side.webp (1672 x 941).\n"
    f"export const SILHOUETTE_VIEWBOX = \"0 0 {P['size'][0]} {P['size'][1]}\";\n\n"
    f"export const SILHOUETTE = {{\n{body},\n}} as const;\n",
    encoding="utf-8",
)
print("wrote", out, sum(len(v) for v in paths.values()), "chars")
